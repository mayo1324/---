"""Builds prototype/js/lessons-extra.js from outputs/lessons/*.json.
New lessons are pushed into LESSONS; "review" objects attach sources to existing lessons (l1..l9).
Run scripts/verify_lessons.py first. Prints the list of scene keys that still have no drawing."""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
art = "".join((ROOT / "prototype" / "js" / n).read_text(encoding="utf-8") for n in ("art.js", "art2.js"))
have = set(re.findall(r"^  ([A-Za-z0-9_]+):", art, re.M)) | set(re.findall(r"SCENES\.([A-Za-z0-9_]+) =", art))
new, src, missing = [], {}, {}
for f in sorted((ROOT / "outputs" / "lessons").glob("*.json")):
    for L in json.loads(f.read_text(encoding="utf-8")):
        refs = [{"u": s["u"]} for s in L.get("src", [])]
        if L.get("review"):
            if L["id"].startswith("l") and L["id"][1:].isdigit():
                src[L["id"]] = refs
            continue
        for s in L["slides"]:
            if s["v"] not in have:
                missing.setdefault(s["v"], []).append(L["id"])
        new.append({"id": L["id"], "title": L["title"], "min": L.get("min", 6), "color": L.get("color", "#c8ff3d"), "module": L["module"],
                    "slides": [{k: v for k, v in s.items() if k in ("t", "b", "v", "w", "x") and v} for s in L["slides"]],
                    "qs": [{"q": q["q"], "o": q["o"], "a": q["a"], "why": q.get("why", "")} for q in L["qs"]],
                    "src": refs, "status": L.get("status", "draft")})
out = ("/* generated by scripts/make_lessons_js.py from outputs/lessons/*.json. Draft lessons, not yet reviewed by an expert. */\n"
       "LESSONS.push(...%s);\n"
       "const LESSON_SRC = %s;\n"
       "LESSONS.forEach(l => { if (!l.src && LESSON_SRC[l.id]) l.src = LESSON_SRC[l.id]; });\n"
       "orderLessons();\n") % (json.dumps(new, ensure_ascii=False, indent=1), json.dumps(src, ensure_ascii=False))
(ROOT / "prototype" / "js" / "lessons-extra.js").write_text(out, encoding="utf-8")
print(f"wrote {len(new)} lessons, sources attached to {sorted(src)}")
print("scene keys without a drawing yet:", {k: sorted(set(v)) for k, v in missing.items()} or "none")
